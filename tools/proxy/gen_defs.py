"""Generate dxgi.def / d3d11.def / d3d12.def from the real system DLLs.

A proxy has to re-export the *entire* export table of the DLL it replaces: if
something in the process imports a function we forgot, the loader fails the load
outright and the game never starts. Hand-maintaining three lists of 20 / 51 / 19
entries is how that goes wrong, so the lists are derived from dumpbin instead.

Names are emitted with their real ordinals. Entries that are ordinal-only on the
target machine are emitted as NONAME with a placeholder symbol, which is how the
system DLL exposes them (d3d12's ordinal 99 is the notable one here).

    python gen_defs.py
    python gen_defs.py --dumpbin "C:/.../dumpbin.exe"
"""

import argparse
import glob
import os
import re
import subprocess

TARGETS = [
    # (system dll, output def, LIBRARY name)
    ("dxgi.dll", "dxgi.def", "dxgi"),
    ("d3d11.dll", "d3d11.def", "d3d11"),
    ("d3d12.dll", "d3d12.def", "d3d12"),
]

ROW = re.compile(r"^\s+(\d+)\s+(?:[0-9A-Fa-f]+)?\s*([0-9A-Fa-f]{8})\s+(\S+)\s*$")
NONAME_ROW = re.compile(r"^\s+(\d+)\s+([0-9A-Fa-f]{8})\s+\[NONAME\]\s*$")


def find_dumpbin():
    hits = glob.glob(
        r"C:\Program Files\Microsoft Visual Studio\**\bin\Hostx64\x64\dumpbin.exe", recursive=True
    )
    if not hits:
        hits = glob.glob(r"C:\Program Files (x86)\Microsoft Visual Studio\**\compiler.exe", recursive=True)
    return hits[0] if hits else None


def parse(dumpbin, dll_path):
    out = subprocess.run(
        [dumpbin, "-exports", dll_path], capture_output=True, text=True, errors="replace"
    ).stdout

    entries = []
    for line in out.splitlines():
        m = NONAME_ROW.match(line)
        if m:
            entries.append((int(m.group(1)), None))
            continue
        m = ROW.match(line)
        if m:
            name = m.group(3)
            # the "name" column for ordinal-only rows is described elsewhere; skip noise
            if name.startswith("[") or name.startswith("."):
                continue
            entries.append((int(m.group(1)), name))

    return entries


def emit(def_path, libname, entries, intercepted):
    """Write one .def.

    Every export is an alias onto an internal `NarakaImpl_*` symbol rather than a
    function literally named after the system export. The SDK headers already
    declare CreateDXGIFactory / D3D11CreateDevice / D3D12CreateDevice etc. with
    their real prototypes; defining same-named functions with proxy-shaped
    signatures collides with them (C2375 / C2733). Aliasing keeps our symbols out
    of the SDK's namespace while still producing an export table identical to the
    system DLL's.
    """
    lines = [
        "; GENERATED by gen_defs.py - do not edit by hand.",
        "; Mirrors the full export table of System32\\%s.dll" % libname,
        "; so that any import the host process makes resolves.",
        "LIBRARY %s" % libname,
        "EXPORTS",
    ]

    for ord_, name in sorted(entries):
        if name is None:
            lines.append("    NarakaOrdinal%d = NarakaImpl_NarakaOrdinal%d @%d NONAME" % (ord_, ord_, ord_))
        else:
            lines.append("    %s = NarakaImpl_%s @%d" % (name, name, ord_))

    with open(def_path, "w", encoding="ascii", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")

    named = sum(1 for _, n in entries if n)
    print("  %-12s %2d entries (%d named)" % (os.path.basename(def_path), len(entries), named))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dumpbin", default=None)
    ap.add_argument("--outdir", default=os.path.dirname(os.path.abspath(__file__)))
    args = ap.parse_args()

    dumpbin = args.dumpbin or find_dumpbin()
    if not dumpbin or not os.path.exists(dumpbin):
        raise SystemExit("dumpbin.exe not found; pass --dumpbin")

    sysdir = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32")
    print("dumpbin: %s" % dumpbin)

    for dll, defname, libname in TARGETS:
        path = os.path.join(sysdir, dll)
        if not os.path.exists(path):
            print("  SKIP %s (not present)" % path)
            continue
        entries = parse(dumpbin, path)
        if not entries:
            raise SystemExit("parsed 0 exports from %s - dumpbin format changed?" % path)
        emit(os.path.join(args.outdir, defname), libname, entries, set())


if __name__ == "__main__":
    main()
